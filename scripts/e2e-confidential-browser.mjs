// Real local escrow operations through the browser, optionally recorded for the demo.
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { chromium, expect } from '@playwright/test';
import { presentation } from '../tools/demo-video/presentation.mjs';
const base = new URL(process.env.APP20_CONFIDENTIAL_BASE_URL ?? 'http://127.0.0.1:5198');
if (base.hostname !== '127.0.0.1' || base.protocol !== 'http:') throw new Error('Disposable loopback lab required.');
const recording = process.env.APP20_DEMO_VIDEO === '1';
const destination = resolve('artifacts/hackathon/confidential');
await mkdir(destination, { recursive: true });
const browser = await chromium.launch();
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, ...(recording ? { recordVideo: { dir: resolve(destination, 'raw'), size: { width: 1440, height: 1000 } } } : {}) });
  const page = await context.newPage(), video = page.video();
  const demo = recording ? await presentation(page, 'confidential-rfq') : undefined;
  const problems = []; page.on('pageerror', error => problems.push(error.message));
  await page.goto(new URL('/rfq/confidential', base).href);
  await expect(page.getByRole('heading', { name: 'Agree on a swap', exact: true })).toBeVisible({ timeout: 180_000 });
  await demo?.mark('Confidential quote'); await demo?.hold(3);
  await page.getByRole('button', { name: 'Create escrow for these terms', exact: true }).click();
  const session = page.getByRole('region', { name: 'Confidential swap session' });
  await expect(session).toBeVisible({ timeout: 120_000 });
  await demo?.mark('Joint setup');
  await page.getByRole('button', { name: 'Approve setup with both demo wallets', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Fund Alice’s side', exact: true })).toBeEnabled({ timeout: 120_000 });
  await demo?.mark('Separate encrypted funding');
  await page.getByRole('button', { name: 'Fund Alice’s side', exact: true }).click();
  await expect(session).toContainText('1 STRK in escrow', { timeout: 120_000 });
  await expect(page.getByRole('button', { name: 'Approve both sides & exchange', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Fund Bob’s side', exact: true }).click();
  await expect(session).toContainText('Both sides funded', { timeout: 120_000 });
  await demo?.mark('Both parties approve the exchange'); await demo?.hold(4);
  await page.getByRole('button', { name: 'Approve both sides & exchange', exact: true }).click();
  await expect(session).toContainText('Both assets were delivered as encrypted notes in one local transaction.', { timeout: 120_000 });
  await demo?.mark('Encrypted exchange completed'); await demo?.hold(5);
  await page.screenshot({ path: resolve(destination, 'settled.png'), fullPage: !recording });

  await page.getByRole('button', { name: 'Create escrow for these terms', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Approve setup with both demo wallets', exact: true })).toBeEnabled({ timeout: 120_000 });
  await page.getByRole('button', { name: 'Approve setup with both demo wallets', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Fund Alice’s side', exact: true })).toBeEnabled({ timeout: 120_000 });
  await page.getByRole('button', { name: 'Fund Alice’s side', exact: true }).click();
  await expect(session).toContainText('1 STRK in escrow', { timeout: 120_000 });
  await demo?.mark('Incomplete trade can expire');
  await page.getByRole('button', { name: 'Advance local time to refund', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Refund Alice', exact: true })).toBeEnabled({ timeout: 120_000 });
  await demo?.mark('Alice recovers independently'); await demo?.hold(3);
  await page.getByRole('button', { name: 'Refund Alice', exact: true }).click();
  await expect(session).toContainText('Funds recovered', { timeout: 120_000 });
  await demo?.mark('Refund completed'); await demo?.hold(4);
  await page.screenshot({ path: resolve(destination, 'refunded.png'), fullPage: !recording });
  assert.deepEqual(problems, []);
  const csrf = await context.request.post(new URL('/__app20_confidential/session', base).href, { headers: { origin: 'https://example.invalid' }, data: { amountA: '1', amountB: '1' } });
  assert.equal(csrf.status(), 403);
  await context.close();
  if (video) await video.saveAs(resolve(destination, 'confidential-rfq.webm'));
  console.log('Browser passed: joint setup, separate funding, encrypted settlement, unilateral timeout refund, cross-origin write rejected.');
} finally { await browser.close(); }
